/** The fills `src/app.css` shipped before the palette-safety redesign, in `FILLS` order. */
const RETIRED = {
  light: ['#245c73', '#176b68', '#956019', '#75558a', '#5d6871'],
  dark: ['#4996b5', '#309b97', '#bb8031', '#9c84ac', '#848e96'],
} as const;

const tokens = (hexes: readonly string[]): Map<string, string> =>
  new Map(FILLS.map((fill, at) => [fill, hexes[at] ?? '']));

describe('palette safety', () => {
  it('P1 matches coloraide on every oracle pair, plain and under protan and deutan', () => {
    expect(ORACLE.length).toBe(54);
    for (const [a, b, plain, protan, deutan] of ORACLE) {
      expect(Math.abs(deltaOk(a, b, 'plain') - plain), `${a} ${b} plain`).toBeLessThan(1e-9);
      expect(Math.abs(deltaOk(a, b, 'protan') - protan), `${a} ${b} protan`).toBeLessThan(1e-9);
      expect(Math.abs(deltaOk(a, b, 'deutan') - deutan), `${a} ${b} deutan`).toBeLessThan(1e-9);
    }
  });

  it('P2 refuses the retired fills by pair, exactly where coloraide puts a pair under a floor', () => {
    for (const theme of ['light', 'dark'] as const) {
      const hexes = RETIRED[theme];
      const expected = ORACLE.filter(
        ([a, b, plain, protan, deutan]) =>
          hexes.includes(a as never) &&
          hexes.includes(b as never) &&
          (plain < 15 || protan < 8 || deutan < 8),
      ).map(
        ([a, b]) =>
          `${FILLS[hexes.indexOf(a as never)] ?? a} vs ${FILLS[hexes.indexOf(b as never)] ?? b}`,
      );
      const refused = gradePalette(FILLS, [[theme, tokens(hexes)]]).failures.map(
        (line) => /^\w+: (\S+ vs \S+) = /u.exec(line)?.[1],
      );
      expect(expected).toHaveLength(7);
      expect([...new Set(refused)]).toEqual(expected);
    }
  });

  it('P3 passes the fills src/app.css ships, in both themes', () => {
    const { light, dark } = themeTokens();
    const { failures, graded } = gradePalette(FILLS, [
      ['light', light],
      ['dark', dark],
    ]);
    expect(failures).toEqual([]);
    expect(graded).toBe(60);
  });

  it('P4 refuses an empty fill table by name', () => {
    expect(gradePalette([], [['light', new Map<string, string>()]]).failures).toEqual([
      'the FILLS table is empty, so it grades no pair',
    ]);
  });
});
